#include <bits/stdc++.h>
using namespace std;
typedef long long ll;

// B 题 寻梅踏雪问春
// 题意：三个整点，问是否存在 r > 0，让以它们为圆心、半径都是 r 的三个圆两两相切。
//
// 两个半径都是 r 的圆相切 <=> 圆心距 = 2r（只能外切：内切要圆心距 = 0 且 r 不同，
// 这里半径相等所以内切不可能）。于是三个圆两两相切 <=> 三条圆心距全都等于 2r，
// 也就是三个点两两等距 —— 三点构成等边三角形。
//
// 判等边：只用比距离的平方（整数运算，没有开方误差）。
// 输入可达 2*10^6，差的平方和最大 8*10^12，必须开 long long。

int main() {
    ll a, b, c, d, e, f;
    cin >> a >> b >> c >> d >> e >> f;                 // 三个点 (a,b) (c,d) (e,f)

    // 三条边的距离平方
    ll ab = (a - c) * (a - c) + (b - d) * (b - d);
    ll cd = (c - e) * (c - e) + (d - f) * (d - f);
    ll ef = (a - e) * (a - e) + (b - f) * (b - f);

    // 三边等长 且 边长不为 0 -> 真正的等边三角形
    // （三点重合时三条距离都是 0，那不是等边三角形：三个圆完全重合，
    //   不满足相切"有且仅有一个公共点"，必须排除）
    if (ab == cd && cd == ef && ab > 0) cout << "YES\n";
    else cout << "NO\n";
    return 0;
}
