#include <bits/stdc++.h>
using namespace std;

// C 题 夜揽星河入梦
// 题意：棋盘上有 n 个互不相同的整数坐标棋子，m 子连珠 = 其中 m 个棋子的坐标排序后
//       是公差 1 的等差数列。初始局面保证没有 m 子连珠。
//       问：再放一个棋子（放在任意整数坐标上），能否出现 m 子连珠。
//
// 关键：等差数列的定义里，公差 d 只是「相邻两项之差相等」，没有规定 d 必须等于 1。
//      但判 m 子连珠时用的是「排序后的 m 个坐标」，而棋盘坐标是整数、棋子坐标互不相同，
//      排序后相邻两项之差 ≥ 1；要构成公差 1 的等差数列，就要求这 m 个坐标恰好是
//      x, x+1, ..., x+m-1 这 m 个连续整数。
//      ==> m 子连珠 ⟺ 存在一段长度为 m 的连续整数区间，这 m 个格子全是棋子。
//
// 所以对每个测试点：求原序列排序后的「最长连续整数段」长度 L。
//   放一个棋子最多让某一段的两端各延伸 1 格，也就是最多把一段变成 L+1（放在段的贴边格）；
//   而且只有这一种可能（新棋子不与任何已有棋子相连时，段长还是 1，没有意义）。
//   于是答案 = (L + 1 >= m) ? YES : NO。
// 等价写法：只要存在某个 x 使得 [x, x+m-1] 里已经有 m-1 个棋子（且缺的那个格子为空），
//   把这个棋子补上就凑齐 m 个。因为原局面没有 m 子连珠，所以 L ≤ m-1，
//   判断 L+1 ≥ m 与「存在 m-1 连」完全等价。

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int T;
    cin >> T;
    while (T--) {
        int n;
        long long m;
        cin >> n >> m;
        vector<long long> a(n);
        for (int i = 0; i < n; ++i) cin >> a[i];
        sort(a.begin(), a.end());                       // 坐标从小到大

        long long best = 1;                             // 最长连续段长度，至少 1
        long long cur = 1;
        for (int i = 1; i < n; ++i) {
            if (a[i] == a[i - 1] + 1) ++cur;            // 与前一个差 1，段继续
            else cur = 1;                               // 断开，重新开始数
            best = max(best, cur);
        }
        // 放一个棋子最多把最长连续段撑到 best+1
        cout << (best + 1 >= m ? "YES" : "NO") << "\n";
    }
    return 0;
}
