// 牛客周赛 Round 123 E. 小红出牌（easy）
// 题意：n 张牌，数字**互不相同**。「顺子」＝ 若干张数字连续（可重排成 x, x+1, ..., x+k-1）的牌。
//       对每个前缀 a[1..x]，求把这些牌全部出成顺子所需的**最少次数**（每个顺子算一次）。
//
// 关键：一个牌集能拆成的最少顺子数 = 这个集合里「连续段」的个数。
//       （同一段连续的牌合成一个顺子最省；分开成两段就一定得两次。）
//       于是只要在线地维护「当前集合有几段」：
//       每来一张新牌，先 +1（它自己算一段），
//       如果 v-1 已经在集合里，就能和左边那段接上 → 段数 -1；
//       如果 v+1 已经在集合里，就能和右边那段接上 → 段数 -1。
//       （左右都在时两张邻牌本来分属两段，接上后合为一段，正好 -2。）
#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;
    vector<char> has(n + 2, 0);        // has[v]：数字 v 是否已经出现过（a_i ≤ n，多开两格防越界）

    long long segs = 0;                // 当前集合的连续段数
    for (int i = 1; i <= n; i++) {
        int v;
        cin >> v;

        has[v] = 1;
        segs++;                        // 新牌先单独算一段
        if (has[v - 1]) segs--;        // 左邻居在 → 并进左边那段
        if (has[v + 1]) segs--;        // 右邻居在 → 并进右边那段

        cout << segs << (i == n ? '\n' : ' ');
    }
    return 0;
}
